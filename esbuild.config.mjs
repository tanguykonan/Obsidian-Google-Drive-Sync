import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import fs from 'fs';

let envClientSecret = process.env.DEFAULT_CLIENT_SECRET || '';
if (!envClientSecret && fs.existsSync('.env')) {
	const envContent = fs.readFileSync('.env', 'utf-8');
	for (const line of envContent.split(/\r?\n/)) {
		const match = line.match(/^\s*DEFAULT_CLIENT_SECRET\s*=\s*(.*)\s*$/);
		if (match) {
			envClientSecret = match[1].trim().replace(/^["']|["']$/g, '');
			break;
		}
	}
}

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	define: {
		'process.env.DEFAULT_CLIENT_SECRET': JSON.stringify(envClientSecret),
	},
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
